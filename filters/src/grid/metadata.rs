//! Shared request-context and metadata contracts for Grid filters.
//!
//! The HTTP headers in this module are AI-owned hop contracts. They deliberately
//! do not use Praxis-reserved `x-praxis-*` names because Praxis strips that
//! namespace before every upstream hop. The owning filter must remove
//! client-supplied values before setting replacements. Provider gateways consume
//! peer fields only after mTLS peer authentication and authorization.

use praxis_filter::HttpFilterContext;
use serde::Deserialize;

/// Selected-candidate header forwarded from the edge gateway.
pub(crate) const SELECTED_CANDIDATE_HEADER: &str = "x-grid-peer-selected-candidate";

/// Per-hop request identifier generated by the edge gateway.
pub(crate) const PROVIDER_HOP_REQUEST_ID_HEADER: &str = "x-grid-peer-hop-request-id";

/// Serving overlay revision forwarded from the edge gateway.
pub(crate) const OVERLAY_REVISION_HEADER: &str = "x-grid-peer-overlay-revision";

/// Provider identity header added only for backend/demo capture.
pub(crate) const PROVIDER_ATTRIBUTION_HEADER: &str = "x-grid-provider-attribution";

/// Correlation header overwritten by the provider gateway for backend capture.
pub(crate) const PROVIDER_REQUEST_ID_HEADER: &str = "x-grid-provider-request-id";

/// Provider-owned copy of the serving overlay revision for backend telemetry.
pub(crate) const PROVIDER_OVERLAY_REVISION_HEADER: &str = "x-grid-provider-overlay-revision";

/// Demo-only response attribution header.
pub(crate) const PROVIDER_ATTRIBUTION_RESPONSE_HEADER: &str = "x-grid-demo-provider-gateway";

/// Admission state of the selected route candidate.
pub(crate) const ROUTE_ADMISSION_STATE: &str = "grid.route.admission_state";
/// Backend cluster selected by `grid_route`.
pub(crate) const ROUTE_CLUSTER: &str = "grid.route.cluster";
/// Candidate kind (e.g. `GridSite`, `CloudManaged`).
pub(crate) const ROUTE_KIND: &str = "grid.route.kind";
/// Local site name of the routing gateway.
pub(crate) const ROUTE_LOCAL_SITE: &str = "grid.route.local_site";
/// Candidate name from the overlay.
pub(crate) const ROUTE_NAME: &str = "grid.route.name";
/// Selection rank within the candidate tier.
pub(crate) const ROUTE_RANK: &str = "grid.route.rank";
/// Selection tier (primary, fallback, etc.).
pub(crate) const ROUTE_SELECTION_TIER: &str = "grid.route.selection_tier";
/// Remote site name of the selected candidate.
pub(crate) const ROUTE_SITE: &str = "grid.route.site";
/// Stable identifier for the selected candidate.
pub(crate) const ROUTE_STABLE_ID: &str = "grid.route.stable_id";
/// Hop request ID forwarded to the provider gateway.
pub(crate) const ROUTE_PROVIDER_HOP_REQUEST_ID: &str = "grid.route.provider_hop_request_id";

/// Candidate ID validated by `grid_provider_route`.
pub(crate) const PROVIDER_ROUTE_CANDIDATE_ID: &str = "grid.provider_route.candidate_id";
/// Provider-local backend cluster.
pub(crate) const PROVIDER_ROUTE_CLUSTER: &str = "grid.provider_route.cluster";
/// Model validated by `grid_provider_route`.
pub(crate) const PROVIDER_ROUTE_MODEL: &str = "grid.provider_route.model";
/// Provider identity for attribution.
pub(crate) const PROVIDER_ROUTE_PROVIDER_ID: &str = "grid.provider_route.provider_id";
/// Provider-scoped request ID.
pub(crate) const PROVIDER_ROUTE_REQUEST_ID: &str = "grid.provider_route.request_id";
/// Serving overlay revision validated by `grid_provider_route`.
pub(crate) const PROVIDER_ROUTE_OVERLAY_REVISION: &str = "grid.provider_route.overlay_revision";

/// Credential injection strategy (e.g. `bearer_token`).
pub(crate) const CREDENTIAL_STRATEGY: &str = "grid.route.credential.strategy";
/// Secret name for credential lookup.
pub(crate) const CREDENTIAL_NAME: &str = "grid.route.credential.name";
/// Secret namespace for credential lookup.
pub(crate) const CREDENTIAL_NAMESPACE: &str = "grid.route.credential.namespace";
/// Secret data key for credential lookup.
pub(crate) const CREDENTIAL_KEY: &str = "grid.route.credential.key";

/// Bearer token injection strategy identifier.
pub(crate) const STRATEGY_BEARER_TOKEN: &str = "bearer_token";

/// Kubernetes Secret reference. Only locator fields are carried in Grid
/// configuration and request metadata.
#[derive(Clone, Debug, Deserialize, Eq, Hash, PartialEq)]
#[serde(deny_unknown_fields)]
pub(crate) struct CredentialRef {
    /// Secret data key.
    pub key: String,
    /// Secret name.
    pub name: String,
    /// Secret namespace.
    pub namespace: String,
}

/// Provider-local reference to credential bytes resolved by
/// `grid_credential_inject`.
#[derive(Clone, Debug, Deserialize, Eq, Hash, PartialEq)]
#[serde(deny_unknown_fields, rename_all = "camelCase")]
pub(crate) struct CandidateCredential {
    /// Injection strategy.
    pub strategy: String,

    /// Secret locator, never secret bytes.
    pub secret_ref: CredentialRef,
}

/// Replace credential-reference metadata with provider-local policy output.
pub(crate) fn set_credential_metadata(ctx: &mut HttpFilterContext<'_>, credential: Option<&CandidateCredential>) {
    clear_credential_metadata(ctx);
    let Some(credential) = credential else {
        return;
    };
    ctx.set_metadata(CREDENTIAL_STRATEGY, &credential.strategy);
    ctx.set_metadata(CREDENTIAL_NAME, &credential.secret_ref.name);
    ctx.set_metadata(CREDENTIAL_NAMESPACE, &credential.secret_ref.namespace);
    ctx.set_metadata(CREDENTIAL_KEY, &credential.secret_ref.key);
}

/// Remove any previously written credential-reference metadata.
pub(crate) fn clear_credential_metadata(ctx: &mut HttpFilterContext<'_>) {
    ctx.filter_metadata.remove(CREDENTIAL_STRATEGY);
    ctx.filter_metadata.remove(CREDENTIAL_NAME);
    ctx.filter_metadata.remove(CREDENTIAL_NAMESPACE);
    ctx.filter_metadata.remove(CREDENTIAL_KEY);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn forwarded_grid_headers_are_not_praxis_reserved() {
        for header in [
            SELECTED_CANDIDATE_HEADER,
            PROVIDER_HOP_REQUEST_ID_HEADER,
            OVERLAY_REVISION_HEADER,
            PROVIDER_ATTRIBUTION_HEADER,
            PROVIDER_OVERLAY_REVISION_HEADER,
            PROVIDER_REQUEST_ID_HEADER,
        ] {
            assert!(
                !praxis_core::reserved_headers::is_reserved(header),
                "{header} would be stripped by the Praxis upstream boundary"
            );
        }
    }

    #[test]
    fn peer_context_uses_fixed_grid_peer_namespace() {
        for header in [
            SELECTED_CANDIDATE_HEADER,
            PROVIDER_HOP_REQUEST_ID_HEADER,
            OVERLAY_REVISION_HEADER,
        ] {
            assert!(
                header.starts_with("x-grid-peer-"),
                "{header} must remain in the Grid peer namespace"
            );
        }
    }
}
