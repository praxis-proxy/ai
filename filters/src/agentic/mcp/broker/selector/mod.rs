#[cfg(test)]
#[expect(clippy::allow_attributes, reason = "blanket test suppressions")]
#[allow(clippy::unwrap_used, clippy::expect_used, reason = "tests")]
mod tests {
    use super::*;

    fn selector() -> Box<dyn HttpFilter> {
        let yaml: serde_yaml::Value = serde_yaml::from_str("clusters: [weather-mcp, calendar-mcp]").unwrap();
        McpBrokerBackendSelectorFilter::from_config(&yaml).unwrap()
    }

    #[test]
    fn declares_cluster_selection() {
        let filter = selector();
        assert!(filter.selects_cluster(), "pipeline checks must see a cluster selector");
        assert_eq!(
            filter.selected_clusters(),
            vec!["weather-mcp".to_owned(), "calendar-mcp".to_owned()],
            "selected clusters must match config"
        );
    }

    #[test]
    fn rejects_empty_cluster_list() {
        let yaml: serde_yaml::Value = serde_yaml::from_str("clusters: []").unwrap();
        assert!(
            McpBrokerBackendSelectorFilter::from_config(&yaml).is_err(),
            "empty cluster list must be rejected"
        );
    }

    #[tokio::test]
    async fn selects_staged_cluster() {
        let filter = selector();
        let req = crate::test_utils::make_request(http::Method::POST, "/mcp");
        let mut ctx = crate::test_utils::make_filter_context(&req);
        ctx.extensions
            .insert(BrokerBackendCluster::new(Arc::from("calendar-mcp"), None));

        let action = filter.on_request(&mut ctx).await.unwrap();

        assert!(matches!(action, FilterAction::Continue), "selector must continue");
        assert_eq!(
            ctx.cluster.as_deref(),
            Some("calendar-mcp"),
            "staged cluster must be selected"
        );
    }

    #[tokio::test]
    async fn pins_staged_endpoint() {
        let filter = selector();
        let req = crate::test_utils::make_request(http::Method::POST, "/mcp");
        let mut ctx = crate::test_utils::make_filter_context(&req);
        ctx.extensions.insert(BrokerBackendCluster::new(
            Arc::from("weather-mcp"),
            Some(Arc::from("10.0.0.2:3001")),
        ));

        let _action = filter.on_request(&mut ctx).await.unwrap();

        assert_eq!(
            ctx.pinned_endpoint_address.as_deref(),
            Some("10.0.0.2:3001"),
            "the session's endpoint must be pinned for the load balancer"
        );
    }

    #[tokio::test]
    async fn unpinned_exchange_leaves_endpoint_choice_to_load_balancer() {
        let filter = selector();
        let req = crate::test_utils::make_request(http::Method::POST, "/mcp");
        let mut ctx = crate::test_utils::make_filter_context(&req);
        ctx.extensions
            .insert(BrokerBackendCluster::new(Arc::from("weather-mcp"), None));

        let _action = filter.on_request(&mut ctx).await.unwrap();

        assert!(ctx.pinned_endpoint_address.is_none(), "no endpoint may be pinned");
    }

    #[tokio::test]
    async fn reports_dialed_endpoint() {
        use praxis_core::connectivity::{ConnectionOptions, Upstream};

        let filter = selector();
        let req = crate::test_utils::make_request(http::Method::POST, "/mcp");
        let mut ctx = crate::test_utils::make_filter_context(&req);
        let staged = BrokerBackendCluster::new(Arc::from("weather-mcp"), None);
        let dialed = Arc::clone(&staged.dialed);
        ctx.extensions.insert(staged);
        ctx.upstream = Some(Upstream {
            address: Arc::from("10.0.0.3:3001"),
            authority: None,
            base_path: None,
            tls: None,
            connection: Arc::new(ConnectionOptions::default()),
        });

        let _action = filter.on_response(&mut ctx).await.unwrap();

        assert_eq!(
            dialed.get().map(AsRef::as_ref),
            Some("10.0.0.3:3001"),
            "the dialed endpoint must reach the broker"
        );
    }

    #[tokio::test]
    async fn follow_up_reaches_the_dialed_endpoint() {
        use praxis_core::connectivity::{ConnectionOptions, Upstream};

        let filter = selector();
        let req = crate::test_utils::make_request(http::Method::POST, "/mcp");
        let mut ctx = crate::test_utils::make_filter_context(&req);
        let staged = BrokerBackendCluster::new(Arc::from("weather-mcp"), None);
        ctx.extensions.insert(staged.clone());
        ctx.upstream = Some(Upstream {
            address: Arc::from("10.0.0.3:3001"),
            authority: None,
            base_path: None,
            tls: None,
            connection: Arc::new(ConnectionOptions::default()),
        });
        let _action = filter.on_response(&mut ctx).await.unwrap();

        let mut extensions = RequestExtensions::default();
        staged.follow_up().stage(&mut extensions);
        let follow_up = extensions.get::<BrokerBackendCluster>().unwrap();
        assert_eq!(&*follow_up.cluster, "weather-mcp", "the same cluster is dialed");
        assert_eq!(
            follow_up.pinned_endpoint.as_deref(),
            Some("10.0.0.3:3001"),
            "an answer on an open stream reaches the endpoint serving it"
        );
        assert!(follow_up.dialed.get().is_none(), "the follow-up records its own dial");
    }

    #[test]
    fn follow_up_keeps_an_existing_pin() {
        let staged = BrokerBackendCluster::new(Arc::from("weather-mcp"), Some(Arc::from("10.0.0.2:3001")));
        let mut extensions = RequestExtensions::default();
        staged.follow_up().stage(&mut extensions);
        assert_eq!(
            extensions
                .get::<BrokerBackendCluster>()
                .unwrap()
                .pinned_endpoint
                .as_deref(),
            Some("10.0.0.2:3001"),
            "a pinned exchange's follow-up keeps the pin"
        );
    }

    #[tokio::test]
    async fn missing_staged_cluster_fails_closed() {
        let filter = selector();
        let req = crate::test_utils::make_request(http::Method::POST, "/mcp");
        let mut ctx = crate::test_utils::make_filter_context(&req);

        assert!(filter.on_request(&mut ctx).await.is_err(), "unstaged request must fail");
        assert!(ctx.cluster.is_none(), "no cluster may be selected");
    }

    #[tokio::test]
    async fn unknown_staged_cluster_fails_closed() {
        let filter = selector();
        let req = crate::test_utils::make_request(http::Method::POST, "/mcp");
        let mut ctx = crate::test_utils::make_filter_context(&req);
        ctx.extensions
            .insert(BrokerBackendCluster::new(Arc::from("other"), None));

        assert!(filter.on_request(&mut ctx).await.is_err(), "unknown cluster must fail");
        assert!(ctx.cluster.is_none(), "no cluster may be selected");
    }
}
