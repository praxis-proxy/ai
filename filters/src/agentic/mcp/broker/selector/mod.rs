//! Cluster selector for MCP broker backend handshake subrequests.
//!
//! The broker generates an outbound chain of this filter, any configured
//! `backend_sessions.outbound_filters`, and a `load_balancer` that references
//! each server's top-level cluster. The broker stages the target cluster as a
//! typed request extension; this filter copies it into `ctx.cluster` so the
//! generated `load_balancer` dials that cluster.
//!
//! A backend session lives on one endpoint, so the selector also pins the
//! exchange to a staged endpoint (`notifications/initialized` and `DELETE`
//! follow the `initialize` that created the session) and reports the endpoint
//! the `load_balancer` dialed back to the broker.
//!
//! As the chain's first filter it also selects a streamed response when the
//! MCP client asks for one, so an SSE handshake reply is read as it arrives.

use std::sync::{Arc, OnceLock};

use async_trait::async_trait;
use praxis_ai_apis::mcp_session::{McpExchangeStage, McpStreamingRequested};
use praxis_filter::{
    BodyAccess, BodyMode, BodyRequirement, FilterAction, FilterError, HttpFilter, HttpFilterContext, RequestExtensions,
    SubRequestResponseMode, parse_filter_config,
};
use serde::Deserialize;

// -----------------------------------------------------------------------------
// Staged Cluster
// -----------------------------------------------------------------------------

/// Destination staged by the broker for one handshake subrequest.
#[derive(Clone, Debug)]
pub(crate) struct BrokerBackendCluster {
    /// Top-level cluster to dial.
    pub(crate) cluster: Arc<str>,
    /// Endpoint the exchange must reach, when a session already lives there.
    pub(crate) pinned_endpoint: Option<Arc<str>>,
    /// Receives the endpoint address the `load_balancer` dialed.
    pub(crate) dialed: Arc<OnceLock<Arc<str>>>,
}

impl BrokerBackendCluster {
    /// Stage `cluster`, optionally pinned to `endpoint`.
    pub(crate) fn new(cluster: Arc<str>, pinned_endpoint: Option<Arc<str>>) -> Self {
        Self {
            cluster,
            pinned_endpoint,
            dialed: Arc::new(OnceLock::new()),
        }
    }
}

impl McpExchangeStage for BrokerBackendCluster {
    fn stage(&self, extensions: &mut RequestExtensions) {
        extensions.insert(self.clone());
    }

    /// Pinned to the endpoint this exchange dialed, or to its own pin. With
    /// neither known the load balancer picks, as it does for the session's
    /// later exchanges.
    fn follow_up(&self) -> Arc<dyn McpExchangeStage> {
        let endpoint = self.dialed.get().cloned().or_else(|| self.pinned_endpoint.clone());
        Arc::new(Self::new(Arc::clone(&self.cluster), endpoint))
    }
}

// -----------------------------------------------------------------------------
// McpBrokerBackendSelectorFilter
// -----------------------------------------------------------------------------

/// Selects the broker-staged backend cluster for an MCP handshake subrequest.
///
/// Generated by the `mcp` broker for `backend_sessions`; operators do not
/// configure it directly. Requests without a staged cluster, or with a
/// cluster outside the configured list, fail closed.
///
/// # YAML
///
/// ```yaml
/// filter: mcp_broker_backend
/// clusters: [weather-mcp, calendar-mcp]
/// ```
pub struct McpBrokerBackendSelectorFilter {
    /// Clusters this selector may assign.
    clusters: Vec<Arc<str>>,
}

/// Raw selector config.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct SelectorConfig {
    /// Clusters this selector may assign.
    clusters: Vec<String>,
}

impl McpBrokerBackendSelectorFilter {
    /// Registered filter name.
    pub(crate) const NAME: &'static str = "mcp_broker_backend";

    /// Create a filter from parsed YAML config.
    ///
    /// # Errors
    ///
    /// Returns [`FilterError`] if the config is invalid or lists no cluster.
    pub fn from_config(config: &serde_yaml::Value) -> Result<Box<dyn HttpFilter>, FilterError> {
        let cfg: SelectorConfig = parse_filter_config(Self::NAME, config)?;
        if cfg.clusters.is_empty() || cfg.clusters.iter().any(String::is_empty) {
            return Err(format!("{}: clusters must be a non-empty list of names", Self::NAME).into());
        }
        Ok(Box::new(Self {
            clusters: cfg.clusters.into_iter().map(Arc::from).collect(),
        }))
    }
}

#[async_trait]
impl HttpFilter for McpBrokerBackendSelectorFilter {
    fn name(&self) -> &'static str {
        "mcp_broker_backend"
    }

    fn selects_cluster(&self) -> bool {
        true
    }

    fn selected_clusters(&self) -> Vec<String> {
        self.clusters.iter().map(ToString::to_string).collect()
    }

    /// The MCP client streams SSE replies; without this declaration Praxis
    /// buffers every callout response.
    fn may_select_streaming_subrequest_response(&self) -> bool {
        true
    }

    /// Read-only, so pipeline finalization keeps the response streamed instead
    /// of clamping it to a size-limited buffered mode.
    fn response_body_access(&self) -> BodyAccess {
        BodyAccess::ReadOnly(BodyRequirement::Optional)
    }

    fn response_body_mode(&self) -> BodyMode {
        BodyMode::Stream
    }

    async fn on_request(&self, ctx: &mut HttpFilterContext<'_>) -> Result<FilterAction, FilterError> {
        let Some(staged) = ctx.extensions.get::<BrokerBackendCluster>() else {
            return Err(format!("{}: no broker backend cluster staged on this request", Self::NAME).into());
        };
        let Some(cluster) = self.clusters.iter().find(|c| c.as_ref() == staged.cluster.as_ref()) else {
            return Err(format!("{}: staged cluster is not configured", Self::NAME).into());
        };
        let pinned = staged.pinned_endpoint.clone();
        ctx.cluster = Some(Arc::clone(cluster));
        ctx.pinned_endpoint_address = pinned;
        if ctx.extensions.get::<McpStreamingRequested>().is_some() {
            ctx.set_subrequest_response_mode(SubRequestResponseMode::Streaming);
        }
        Ok(FilterAction::Continue)
    }

    async fn on_response(&self, ctx: &mut HttpFilterContext<'_>) -> Result<FilterAction, FilterError> {
        if let (Some(staged), Some(upstream)) = (ctx.extensions.get::<BrokerBackendCluster>(), ctx.upstream.as_ref()) {
            let _already_set = staged.dialed.set(Arc::clone(&upstream.address));
        }
        Ok(FilterAction::Continue)
    }
}

